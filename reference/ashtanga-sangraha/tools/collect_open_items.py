#!/usr/bin/env python3
"""Collect every unresolved observation of the layer work into layers-work/OPEN_ITEMS.md.
Sources (nothing is deleted or hidden):
  1. review issues without a machine patch (chunkK_review.json, chunkK_enrich_review.json)
  2. text_flags of every final chunk (suspected misprints, to be checked against the print)
  3. units with confidence "low"
  4. manual files (chunkK_MANUAL.md)
Usage: collect_open_items.py BOOK_DIR"""
import json, sys
from pathlib import Path

book = Path(sys.argv[1]); work = book / "layers-work" / "p05"
out = ["# Open items (collected, not yet resolved)", "",
       "Generated by tools/collect_open_items.py. Every observation made by the drafting and review passes that was not fixed by a patch is listed here for the owner to resolve at the end. Nothing here has been decided.", ""]
tot = {"issues": 0, "flags": 0, "low": 0}
def units(d):
    return d if isinstance(d, list) else d.get("units", [])
for chdir in sorted(work.glob("ch*")):
    sec = []
    for kind in ("review", "enrich_review"):
        for f in sorted(chdir.glob(f"chunk*_{kind}.json")):
            k = f.name.split("_")[0][5:]
            try: rv = json.load(open(f, encoding="utf-8"))
            except Exception: continue
            for u in units(rv):
                for it in u.get("issues", []):
                    if it.get("patch"): continue
                    tot["issues"] += 1
                    sec.append(f"- [{kind.replace('_',' ')}, chunk {k}, unit {u.get('n')}, {it.get('severity','?')}] {it.get('field','')} / {str(it.get('where',''))[:80]}: {it.get('problem','').strip()}" + (f" Suggested: {it['fix']}" if it.get("fix") else ""))
    for f in sorted(chdir.glob("chunk*_final.json")):
        if "pre-enrich" in f.name: continue
        k = f.name.split("_")[0][5:]
        for u in units(json.load(open(f, encoding="utf-8"))):
            for tf in u.get("text_flags", []):
                tot["flags"] += 1
                sec.append(f"- [text_flag, chunk {k}, unit {u.get('n')}] printed `{tf.get('src')}` -> `{tf.get('suggest')}`: {tf.get('why','')}")
            if u.get("confidence") == "low":
                tot["low"] += 1
                sec.append(f"- [low confidence, chunk {k}, unit {u.get('n')}] {str(u.get('notes',''))[:200]}")
    for f in sorted(chdir.glob("chunk*_MANUAL.md")):
        sec.append(f"- [manual file] {f.name}: " + f.read_text(encoding="utf-8").strip().replace("\n", " ")[:400])
    if sec:
        out += [f"## {chdir.name}", ""] + sec + [""]
out.insert(3, f"Totals: {tot['issues']} review issues without a patch, {tot['flags']} text flags, {tot['low']} low-confidence units.")
(book / "layers-work" / "OPEN_ITEMS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(tot)
